async function upsertDoc(category, title, content) {
  const ex = await prisma.knowledgeEntry.findFirst({ where: { projectId: PID, category, title } });
  if (ex) {
    if (ex.content === content && ex.isActive) return 'без змін';
    if (APPLY) await prisma.knowledgeEntry.update({ where: { id: ex.id }, data: { content, isActive: true, addedBy: 'user' } });
    return 'оновлено';
  }
  if (APPLY) await prisma.knowledgeEntry.create({ data: { projectId: PID, category, title, content, addedBy: 'user' } });
  return 'створено';
}

