import { describe, it, expect } from "vitest";
import { scanWriting } from "./writingGate";

describe("scanWriting (C3 grep-gate)", () => {
  it("ловить стоп-слова, щільність тире й привітання", () => {
    const bad = "Друзі, сьогодні поговоримо. Таким чином, це — важливо — і корисно — тут. Безумовно, у сучасному світі кожен з нас це знає.";
    const v = scanWriting(bad);
    const types = new Set(v.map((x) => x.type));
    expect(v.length).toBeGreaterThan(0);
    expect(types.has("banned_word")).toBe(true);
    expect(types.has("dash_overuse")).toBe(true);
    expect(types.has("greeting_start")).toBe(true);
  });

  it("пропускає чистий людський текст (0 порушень)", () => {
    const good = "Заявка прийшла о 14:38.\n\nВласник дізнався о 19:00. Клієнт уже купив в іншого.";
    expect(scanWriting(good)).toEqual([]);
  });

  it("одне тире в абзаці — ок, два — порушення", () => {
    expect(scanWriting("Це нормально — одне тире на абзац.")).toEqual([]);
    expect(scanWriting("Це — забагато — тире в абзаці.").some((x) => x.type === "dash_overuse")).toBe(true);
  });

  it("буліт-список («— пункт» на початку рядка) — НЕ dash_overuse (регрес 2026-09-30)", () => {
    // Реальний кейс, який гейт хибно відхиляв: KIRO-пост зі списком "Зробив:" тримав
    // 3 пости в чернетках хоча жодного em-dash overuse в прозі немає — це буліти.
    const bulletList = "Зробив:\n— Додаток пройшов внутрішнє тестування\n— Відправив на перевірку в Google Play\n— Почав готувати App Store";
    expect(scanWriting(bulletList).some((x) => x.type === "dash_overuse")).toBe(false);
  });

  it("буліт-список НЕ маскує справжнє зловживання тире всередині одного з пунктів", () => {
    const mixed = "Зробив:\n— перше — друге — третє в одному рядку\n— просто пункт";
    expect(scanWriting(mixed).some((x) => x.type === "dash_overuse")).toBe(true);
  });

  it("нумерований список («1. Назва — опис») — теж НЕ dash_overuse (регрес 2026-09-30)", () => {
    // Реальний кейс: KIRO-пост "5 типів подій" з 5 пунктами "N. Назва — опис" в одному
    // абзаці (без порожніх рядків між пунктами) — гейт рахував це як "5 тире".
    const numbered =
      "5 типів подій:\n1. Велозбори — анонсуються за добу\n2. Ігрові вечори — мафія, кешфлоу\n3. Пікніки — з незнайомцями\n4. Розмовні клуби — раз на тиждень\n5. Майстер-класи — часто безкоштовні";
    expect(scanWriting(numbered).some((x) => x.type === "dash_overuse")).toBe(false);
  });

  it("нумерований список НЕ маскує зловживання тире всередині одного пункту", () => {
    const numbered = "1. Назва — опис — і ще щось — і ще одне уточнення\n2. Друга назва — опис";
    expect(scanWriting(numbered).some((x) => x.type === "dash_overuse")).toBe(true);
  });

  it("звичайна проза з кількома тире (не список) — досі порушення", () => {
    // Реальний кейс, де правило спрацьовує правильно: тире як стилістичний прийом
    // усередині суцільного речення, не структура списку.
    const prose = "Знайшов концерт — білети продані. Знайшов пікнік — вже вчора. Знайшов майстер-клас — реєстрація закрита.";
    expect(scanWriting(prose).some((x) => x.type === "dash_overuse")).toBe(true);
  });

  it("абзац з ОДНИМ буліт-пунктом (не списком з 2+) теж не фолсить (регрес фіксу вище)", () => {
    // Перша версія фіксу вимагала 2+ рядків-пунктів, щоб визнати абзац списком — і тому
    // хибно ловила "2 тире" на одному буліт-пункті з одним ЗВИЧАЙНИМ тире всередині
    // речення (реальний кейс: KIRO-пост "Де застряг:\n— ... Тому чекаю — і шукаю людей").
    const singleBullet = "Де застряг:\n— Причина. Тому чекаю — і шукаю людей :)";
    expect(scanWriting(singleBullet).some((x) => x.type === "dash_overuse")).toBe(false);
  });
});
